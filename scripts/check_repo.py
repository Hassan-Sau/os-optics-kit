def check_links(root: Path, name: str, text: str, problems: Problems) -> None:
    # Blank out code so examples of link syntax are not links; keep offsets for line numbers.
    masked = FENCE.sub(lambda match: re.sub(r"[^\n]", " ", match.group(0)), text)
    masked = INLINE_CODE.sub(lambda match: " " * len(match.group(0)), masked)
    targets = [(match.start(1), match.group(1)) for pattern in (LINK, REFERENCE, HTML_LINK)
               for match in pattern.finditer(masked)]
    for index, target in sorted(targets):
        if SCHEME.match(target) or target.startswith(("#", "//")):
            continue
        path = unquote(target.split("#", 1)[0].split("?", 1)[0])
        if not path:
            continue
        base = root if path.startswith("/") else (root / name).parent
        resolved = (base / path.lstrip("/")).resolve()
        if not resolved.is_relative_to(root.resolve()):
            problems.add("links", name, f"link {target} points outside the repository", line_of(text, index))
        elif not resolved.exists():
            problems.add("links", name, f"link {target} does not resolve", line_of(text, index))


def check_size(root: Path, name: str, problems: Problems) -> None:
    size = (root / name).stat().st_size
    image = PurePosixPath(name).suffix.lower() in IMAGE_SUFFIXES
    limit = MAX_IMAGE_BYTES if image else MAX_FILE_BYTES
    if size > limit:
        kind = "image" if image else "file"
        problems.add("size", name, f"{kind} has {size} bytes; the limit is {limit} bytes")


def check_forbidden(name: str, problems: Problems) -> None:
    path = PurePosixPath(name)
    folders = path.parts[:-1]
    if path.name.lower() in WORK_LOGS:
        problems.add("forbidden", name, "work log; record changes in CHANGELOG.md, commit messages and pull "
                                        "requests instead")
    elif path.name in FORBIDDEN_NAMES or path.suffix.lower() in FORBIDDEN_SUFFIXES \
            or FORBIDDEN_PATTERN.search(path.name):
        problems.add("forbidden", name, "generated output, binary package, key or catalog release; keep it out of "
                                        "the repository")
    elif len(folders) >= 3 and folders[0] == "cases" \
            and any(folder == "out" or folder.startswith("run") for folder in folders[2:]):
        problems.add("forbidden", name, "run directory inside a case; keep run outputs out of the repository")


def check_text(name: str, text: str, problems: Problems) -> None:
    for pattern in MACHINE_PATHS:
        for match in pattern.finditer(text):
            problems.add("paths", name, f"absolute machine path {match.group(0)!r}; use a relative or "
                                        "placeholder path", line_of(text, match.start()))
    for number, pattern in enumerate(LEAK_PATTERNS, 1):
        for match in pattern.finditer(text):
            problems.add("secrets", name, f"matches credential pattern {number} (see LEAK_PATTERNS); remove it and "
                                          "revoke it",
                         line_of(text, match.start()))
    for host in RETIRED_HOSTS:
        escaped = re.escape(host).replace(r"\-", "-+")  # shields.io badges write "-" as "--"
        for match in re.finditer(r"(?<!\w)" + escaped + r"(?!\w)", text, re.I):
            problems.add("pins", name, f"retired host {match.group(0)}; use opensci-optics.com",
                         line_of(text, match.start()))


def in_pin_scope(name: str) -> bool:
    return not name.startswith(PIN_EXEMPT)


def check_pins(name: str, text: str, baseline: dict, problems: Problems) -> None:
    # While a candidate engine is being verified, install pins name the candidate (the kit requires it).
    stated = baseline.get("engine") or {}
    engine = stated.get("candidate_version") or stated.get("verified_version")
    kit = baseline.get("kit_version")
    for pattern, expected, label in ((ENGINE_PIN, engine, "os-optics"), (KIT_PIN, kit, "os-optics-kit")):
        for match in pattern.finditer(text):
            if expected and match.group(1) != expected:
                problems.add("pins", name, f"{label} pin {match.group(1)} differs from baseline.json {expected}",
                             line_of(text, match.start()))
    for match in RETIRED_PIN.finditer(text):
        problems.add("pins", name, "pin of the former engine distribution name; use os-optics",
                     line_of(text, match.start()))


def check_ranges(name: str, text: str, baseline: dict, problems: Problems) -> None:
    requirement = (baseline.get("engine") or {}).get("requirement")
    if not isinstance(requirement, str) or name in RANGE_EXEMPT:
        return
    for match in ENGINE_RANGE.finditer(text):
        if specifier_clauses(match.group(1)) != specifier_clauses(requirement):
            stated = re.sub(r"\s+", "", match.group(1))
            problems.add("ranges", name, f"os-optics range {stated} differs from baseline.json engine.requirement "
                                         f"{requirement}",
                         line_of(text, match.start()))


def in_statement_scope(name: str) -> bool:
    return name in STATEMENT_DOCUMENTS or (name.startswith("docs/") and name.endswith(".md"))


def check_statements(name: str, text: str, baseline: dict, problems: Problems) -> None:
    """Version and catalog statements of the kit's own documents agree with baseline.json (``statements``)."""
    engine = baseline.get("engine") or {}
    requirement, verified = engine.get("requirement"), engine.get("verified_version")
    kit = baseline.get("kit_version")
    catalog = (baseline.get("catalog") or {}).get("version")
    if isinstance(requirement, str):
        for match in ENGINE_SERIES.finditer(text):
            try:
                inside = satisfies(match.group(1), requirement)
            except ValueError:
                inside = False
            if not inside:
                problems.add("statements", name, f"names os-optics {match.group(1)}, outside baseline.json "
                                                  f"engine.requirement {requirement}", line_of(text, match.start()))
    if isinstance(kit, str):
        series = ".".join(kit.split(".")[:2])
        for match in KIT_SERIES.finditer(text):
            if match.group(1) != series:
                problems.add("statements", name, f"names os-optics-kit {match.group(1)}; baseline.json kit_version "
                                                  f"is {kit}", line_of(text, match.start()))
    if isinstance(verified, str):
        for match in VERIFIED_ENGINE.finditer(text):
            if match.group(1) != verified:
                problems.add("statements", name, f"states verification with os-optics {match.group(1)}; "
                                                  f"baseline.json engine.verified_version is {verified}",
                             line_of(text, match.start()))
    if isinstance(catalog, str):
        for match in CATALOG_RELEASE.finditer(text):
            if match.group(1) != catalog:
                problems.add("statements", name, f"names catalog release {match.group(1)}; baseline.json "
                                                  f"catalog.version is {catalog}", line_of(text, match.start()))


def front_matter(text: str) -> dict[str, str]:
    """``key: value`` lines of a leading ``---`` block (the scalar fields a case states)."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    fields = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, colon, value = line.partition(":")
        if colon and key and not key.startswith((" ", "\t", "-")):
            fields[key.strip()] = value.strip()
    return fields


def check_cases(root: Path, names: list[str], baseline: dict, problems: Problems) -> None:
    """Each case states one engine and catalog: front matter, expected.json and prose agree with each other and
    with baseline.json (``cases``).

    The engine is ``engine.verified_version``, or ``engine.candidate_version`` while one is set: a case that needs
    the candidate engine (a feature the verified one lacks) is recorded on it, which its CASE.md front matter and
    its expected.json must both state."""
    verified = (baseline.get("engine") or {}).get("verified_version")
    candidate = (baseline.get("engine") or {}).get("candidate_version")
    catalog = (baseline.get("catalog") or {}).get("version")
    present = set(names)
    for case_file in sorted(n for n in names if re.fullmatch(r"cases/[^/]+/CASE\.md", n)):
        folder = case_file[:-len("CASE.md")]
        text = read_text(root / case_file) or ""
        fields = front_matter(text)
        engine, case_catalog = fields.get("engine"), fields.get("catalog")
        expected_name = folder + "expected.json"
        expected = None
        if expected_name in present:
            try:
                expected = json.loads((root / expected_name).read_text(encoding="utf-8"))
            except (OSError, ValueError):
                pass  # reported by the json check
        if engine is not None and isinstance(verified, str) and engine != verified:
            if isinstance(candidate, str) and engine == candidate:
                # Accepted only with its record: an expected.json that disagrees is reported below.
                if not isinstance(expected, dict):
                    problems.add("cases", case_file, f"engine {engine} is baseline.json engine.candidate_version; a "
                                                     f"case recorded on the candidate engine needs an expected.json "
                                                     f"that records it too")
            else:
                allowed = f"engine.verified_version {verified}" + (
                    f" or engine.candidate_version {candidate}" if isinstance(candidate, str) else "")
                problems.add("cases", case_file, f"engine {engine} differs from baseline.json {allowed}; re-verify "
                                                 f"the case or keep the baseline")
        if case_catalog not in (None, "none") and isinstance(catalog, str) and case_catalog != catalog:
            problems.add("cases", case_file, f"catalog {case_catalog} differs from baseline.json catalog.version "
                                             f"{catalog}")
        if expected_name in present:
            if isinstance(expected, dict):
                if engine is not None and expected.get("engine") != engine:
                    problems.add("cases", expected_name, f"engine {expected.get('engine')!r} differs from CASE.md "
                                                         f"engine {engine}")
                stated = None if case_catalog in (None, "none") else case_catalog
                if case_catalog is not None and expected.get("catalog") != stated:
                    problems.add("cases", expected_name, f"catalog {expected.get('catalog')!r} differs from CASE.md "
                                                         f"catalog {case_catalog}")
        for document in (case_file, folder + "README.md", folder + "README.zh-CN.md"):
            if document not in present:
                continue
            prose = read_text(root / document) or ""
            if engine is not None:
                for pattern in (CASE_BASELINE_LINE, VERIFIED_ENGINE):
                    for match in pattern.finditer(prose):
                        if match.group(1) != engine:
                            problems.add("cases", document, f"names os-optics {match.group(1)} as the verified "
                                                            f"engine; the case records {engine}",
                                         line_of(prose, match.start()))
            if case_catalog is not None:
                for match in CATALOG_RELEASE.finditer(prose):
                    if match.group(1) != case_catalog:
                        problems.add("cases", document, f"names catalog release {match.group(1)}; the case records "
                                                        f"{case_catalog}", line_of(prose, match.start()))


def check_changelog(root: Path, baseline: dict, problems: Problems) -> None:
    """A section ``## X.Y.Z`` per release, newest first; the newest is the baseline's ``kit_version``."""
    path = root / CHANGELOG
    if not path.is_file():
        problems.add("changelog", CHANGELOG, "missing; it holds one section per release, newest first")
        return
    text = path.read_text(encoding="utf-8")
    headings = [(match.group(1), line_of(text, match.start())) for match in RELEASE_HEADING.finditer(text)]
    previous = None
    seen = set()
    releases = []
    for index, (version, line) in enumerate(headings):
        if version == UNRELEASED:  # changes merged since the last release, above every release
            if index:
                problems.add("changelog", CHANGELOG, f"section '## {UNRELEASED}' comes before every release", line)
            continue
        if not RELEASE_VERSION.fullmatch(version):
            problems.add("changelog", CHANGELOG, f"section heading {version!r} is not a release version", line)
            continue
        releases.append((version, line))
        if version in seen:
            problems.add("changelog", CHANGELOG, f"section {version} appears twice", line)
        elif previous is not None and _version_tuple(version) >= _version_tuple(previous):
            problems.add("changelog", CHANGELOG, f"section {version} follows {previous}; list releases newest "
                                                 "first", line)
        seen.add(version)
        previous = version
    kit = baseline.get("kit_version")
    if not isinstance(kit, str):
        return
    if kit not in seen:
        problems.add("changelog", CHANGELOG, f"no section '## {kit}' for kit_version {kit} of baseline.json")
    elif releases[0][0] != kit:
        problems.add("changelog", CHANGELOG, f"the first section is {releases[0][0]}; the newest release "
                                             f"{kit} (kit_version of baseline.json) comes first", releases[0][1])


def check_json(root: Path, name: str, problems: Problems) -> None:
    try:
        json.loads((root / name).read_text(encoding="utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        problems.add("json", name, f"invalid JSON: {exc}")


def specifier_clauses(requirement: str) -> frozenset[str]:
    """Order-independent form of a specifier: ``>=0.12,<0.13`` equals ``<0.13, >=0.12``."""
    return frozenset(clause for clause in re.sub(r"\s+", "", requirement).split(",") if clause)


def _version_tuple(text: str) -> tuple[int, ...]:
    match = re.match(r"\d+(?:\.\d+)*", text)
    if not match:
        raise ValueError(f"not a version: {text!r}")
    parts = [int(part) for part in match.group(0).split(".")]
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def satisfies(version: str, requirement: str) -> bool:
    """Evaluate a comma-separated specifier with ==, !=, >=, <=, >, < (release segments only)."""
    try:
        from packaging.specifiers import SpecifierSet
        from packaging.version import Version
        return Version(version) in SpecifierSet(requirement)
    except ImportError:
        pass
    value = _version_tuple(version)
    operators = {">=": lambda a, b: a >= b, "<=": lambda a, b: a <= b, ">": lambda a, b: a > b,
                 "<": lambda a, b: a < b, "==": lambda a, b: a == b, "!=": lambda a, b: a != b}
    for clause in filter(None, (part.strip() for part in requirement.split(","))):
        match = re.fullmatch(r"(>=|<=|==|!=|>|<)\s*(\S+)", clause)
        if not match:
            raise ValueError(f"unsupported specifier {clause!r}")
        if not operators[match.group(1)](value, _version_tuple(match.group(2))):
            return False
    return True


def check_baseline(root: Path, problems: Problems) -> dict:
    name = "baseline.json"
    try:
        baseline = json.loads((root / name).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        problems.add("baseline", name, f"cannot read: {exc}")
        return {}
    if not isinstance(baseline, dict):
        problems.add("baseline", name, "expected an object")
        return {}
    engine: dict = baseline["engine"] if isinstance(baseline.get("engine"), dict) else {}
    catalog: dict = baseline["catalog"] if isinstance(baseline.get("catalog"), dict) else {}
    expected = {"schema": "os-optics-kit.baseline", "schema_version": 1}
    for key, value in expected.items():
        if baseline.get(key) != value:
            problems.add("baseline", name, f"{key} must be {value!r}")
    if engine.get("distribution") != "os-optics":
        problems.add("baseline", name, "engine.distribution must be 'os-optics'")
    if not re.fullmatch(r"20\d\d-\d\d-\d\d\.\d+", str(catalog.get("version"))):
        problems.add("baseline", name, "catalog.version must be a release such as 2026-10-28.1")
    if not re.fullmatch(r"\d+\.\d+", str(catalog.get("schema_version"))):
        problems.add("baseline", name, "catalog.schema_version must be a string such as '3.2'")
    if not re.fullmatch(r"[0-9a-f]{64}", str(catalog.get("sha256"))):
        problems.add("baseline", name, "catalog.sha256 must be 64 lower-case hexadecimal characters")
    python = baseline.get("python")
    if not isinstance(python, list) or not python or not all(
            isinstance(item, str) and re.fullmatch(r"3\.\d+", item) for item in python):
        problems.add("baseline", name, "python must be a non-empty list such as ['3.11', '3.14']")
        python = []

    version_file = root / "tools" / "os_optics_kit" / "_version.py"
    try:
        match = re.search(r"^__version__ = \"([^\"]+)\"", version_file.read_text(encoding="utf-8"), re.M)
        source_version = match.group(1) if match else None
    except OSError:
        source_version = None
    if baseline.get("kit_version") != source_version:
        problems.add("baseline", name, f"kit_version {baseline.get('kit_version')!r} differs from "
                                       f"tools/os_optics_kit/_version.py {source_version!r}")
    engine_file = root / "tools" / "os_optics_kit" / "_engine.py"
    if engine_file.is_file():
        source = engine_file.read_text(encoding="utf-8")
        for key, constant in (("distribution", "ENGINE_DISTRIBUTION"), ("requirement", "ENGINE_REQUIREMENT")):
            found = re.search(rf"^{constant} = \"([^\"]*)\"", source, re.M)
            stated = found.group(1) if found else None
            if stated is None or specifier_clauses(stated) != specifier_clauses(str(engine.get(key))):
                problems.add("baseline", name, f"engine.{key} {engine.get(key)!r} differs from "
                                               f"tools/os_optics_kit/_engine.py {constant} {stated!r}")

    if tomllib is None:
        return baseline
    try:
        project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    except (OSError, KeyError, ValueError) as exc:
        problems.add("baseline", "pyproject.toml", f"cannot read [project]: {exc}")
        return baseline
    specifiers = [dependency[len("os-optics"):] for dependency in project.get("dependencies", [])
                  if re.match(r"os-optics(?![\w-])", dependency)]
    requirement = re.sub(r"\s+", "", str(engine.get("requirement")))
    if [specifier_clauses(item) for item in specifiers] != [specifier_clauses(requirement)]:
        problems.add("baseline", name, f"engine.requirement {engine.get('requirement')!r} differs from the "
                                       f"pyproject.toml os-optics dependency {specifiers}")
    verified = engine.get("verified_version")
    candidate = engine.get("candidate_version")
    try:
        if candidate is not None:
            # Transitional: the kit requires a candidate engine that has not been verified yet. The verified
            # version stays the last one actually verified; a release build refuses while this is set.
            if not isinstance(candidate, str) or not satisfies(candidate, requirement):
                problems.add("baseline", name, f"engine.candidate_version {candidate!r} is outside {requirement}")
            elif not isinstance(verified, str) or _version_tuple(verified) >= _version_tuple(candidate):
                problems.add("baseline", name, f"engine.verified_version {verified!r} must precede "
                                               f"engine.candidate_version {candidate!r}")
        elif not isinstance(verified, str) or not satisfies(verified, requirement):
            problems.add("baseline", name, f"engine.verified_version {verified!r} is outside {requirement}")
    except ValueError as exc:
        problems.add("baseline", name, f"engine.requirement: {exc}")
    minimum = re.fullmatch(r">=\s*(3\.\d+)", str(project.get("requires-python", "")).strip())
    classifiers = set(project.get("classifiers", []))
    for item in python:
        if minimum and _version_tuple(item) < _version_tuple(minimum.group(1)):
            problems.add("baseline", name, f"python {item} is older than requires-python {minimum.group(0)}")
        if f"Programming Language :: Python :: {item}" not in classifiers:
            problems.add("baseline", name, f"python {item} has no 'Programming Language :: Python :: {item}' "
                                           "classifier in pyproject.toml")
    return baseline


def check_pairs(names: list[str], problems: Problems) -> None:
    present = set(names)
    for name in names:
        if name.startswith("docs/en/") and name.endswith(".md"):
            partner = "docs/zh-CN/" + name[len("docs/en/"):]
        elif name.startswith("docs/zh-CN/") and name.endswith(".md"):
            partner = "docs/en/" + name[len("docs/zh-CN/"):]
        elif name.endswith(".zh-CN.md"):
            partner = name[:-len(".zh-CN.md")] + ".md"
        elif name == "README.md":
            partner = "README.zh-CN.md"
        else:
            continue
        if partner not in present:
            problems.add("pairs", name, f"missing its language counterpart {partner}")


def run_checks(root: Path) -> dict:
    root = root.resolve()
    problems = Problems()
    names = repository_files(root)
    baseline = check_baseline(root, problems)
    for name in names:
        check_size(root, name, problems)
        check_forbidden(name, problems)
        suffix = PurePosixPath(name).suffix.lower()
        if suffix == ".json":
            check_json(root, name, problems)
        if suffix in IMAGE_SUFFIXES - {".svg"}:
            continue
        text = read_text(root / name)
        if text is None:
            continue
        check_text(name, text, problems)
        if suffix == ".md":
            check_links(root, name, text, problems)
        if in_pin_scope(name):
            check_pins(name, text, baseline, problems)
            check_ranges(name, text, baseline, problems)
        if in_statement_scope(name):
            check_statements(name, text, baseline, problems)
    check_cases(root, names, baseline, problems)
    check_changelog(root, baseline, problems)
    check_pairs(names, problems)
    items = sorted(problems.items, key=lambda item: (item["check"], item["path"], item["line"] or 0))
    return {"status": "FAIL" if items else "PASS", "files": len(names), "problems": items}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT, help="Repository root (default: this checkout)")
    args = parser.parse_args(argv)
    result = run_checks(args.root)
    print(json.dumps(result, ensure_ascii=False, separators=(",", ":")))
    if os.environ.get("GITHUB_ACTIONS") == "true":
        for item in result["problems"]:
            location = f"file={item['path']}" + (f",line={item['line']}" if item["line"] else "")
            message = item["message"].replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
            print(f"::error {location},title=check_repo {item['check']}::{message}", file=sys.stderr)
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
